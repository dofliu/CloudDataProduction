# 與升級前相同的版面常數(mm):字高 ±60、字寬 60、字距 40,行程限制 ±220。
Y_TOP, Y_BOT = -60.0, 60.0
GLYPH_W, GLYPH_GAP = 60.0, 40.0
MAX_WIDTH = 440.0            # 總寬超過就整體等比縮小(X/Y 同縮,字不變形)

MAX_CHARS = 8                # engrave_char_1..8


def codes_to_text(codes: list[int]) -> str:
    """setpoint 的 ASCII 碼列 → 文字。0 視為空白;不在字型裡的碼也視為空白;去尾端空白。"""
    chars = []
    for c in codes[:MAX_CHARS]:
        ch = chr(int(c)).upper() if 32 <= int(c) < 127 else " "
        chars.append(ch if ch in GLYPHS else " ")
    return "".join(chars).rstrip()


def text_strokes(text: str) -> list[list[tuple[float, float]]]:
    """文字 → 引擎座標(mm)的筆畫列表,水平置中、超寬時等比縮小。

    空白佔字位但不出筆畫(所以 "AB CD" 中間真的空一格)。全空 → 回傳空列表,
    由呼叫端決定停刀(park)行為。
    """
    text = text[:MAX_CHARS]
    n = len(text)
    if n == 0:
        return []
    total = n * GLYPH_W + (n - 1) * GLYPH_GAP
    s = min(1.0, MAX_WIDTH / total)
    w, gap = GLYPH_W * s, GLYPH_GAP * s
    y_top, y_bot = Y_TOP * s, Y_BOT * s
    left0 = -(n * w + (n - 1) * gap) / 2
    out: list[list[tuple[float, float]]] = []
    for i, ch in enumerate(text):
        left = left0 + i * (w + gap)
        for stroke in GLYPHS.get(ch, []):
            out.append([(left + xu * w, y_top + yu * (y_bot - y_top)) for xu, yu in stroke])
    return out
